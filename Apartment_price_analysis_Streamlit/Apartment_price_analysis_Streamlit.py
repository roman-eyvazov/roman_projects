object_type = {'Первичный': '0', 'Вторичный': '2'}
df['object_type'] = df['object_type'].map(object_type)

# id_region должен быть категориальным признаком
df['id_region'] = df['id_region'].astype('object')

# новый признак level_ratio
df['level_ratio'] = df['level'] / df['levels']

# категориальные и числовые признаки
cat_features = df.select_dtypes(include='object').columns.tolist()
