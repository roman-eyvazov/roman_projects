# загрузка предобученного ColumnTransformer
# ВНИМАНИЕ - необходимо использовать версию sklearn 1.6.1 !!!
col_tr = joblib.load('ColumnTransformer')

# применяем ColumnTransformer
X_scaled = pd.DataFrame(col_tr.transform(df),
						columns=col_tr.get_feature_names_out())

# оптимизируем типы данных
ohe_columns = [col for col in X_scaled.columns if col.startswith('ohe')]
scaled_columns = list(set(X_scaled.columns) - set(ohe_columns))
X_fin = X_scaled.loc[:, ohe_columns].astype('uint8'). \
		join(X_scaled.loc[:, scaled_columns].astype('float32'))

# загрузка предобученного XGBoost
xgbst = joblib.load('XGBoost_model')
# ВНИМАНИЕ - порядок признаков в датафрейме должен совпадать с порядком
# признаков в обученном XGBoost !!!
# получаем признаки в правильном порядке из XGBoost
cols_xgbst = xgbst.get_booster().feature_names
# упорядочиваем как нужно
X_fin = X_fin[cols_xgbst]

# делаем предсказание
y_pred = xgbst.predict(X_fin)

