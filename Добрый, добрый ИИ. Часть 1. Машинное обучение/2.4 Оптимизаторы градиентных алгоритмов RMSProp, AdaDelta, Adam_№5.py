import numpy as np
import matplotlib.pyplot as plt

# логарифмическая функция потерь
def loss(w, x, y):
    M = np.dot(w, x.T) * y
    return np.log2(1 + np.exp(-M))


# производная логарифмической функции потерь по вектору w
def df(w, x, y):
    M = np.dot(w, x.T) * y
    return -(np.exp(-M) * x.T * y) / ((1 + np.exp(-M)) * np.log(2))


