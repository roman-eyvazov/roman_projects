X_train = np.array([[1, x[0], x[1]] for x in data_x])
y_train = data_y

n_train = len(X_train) # размер обучающей выборки
w = [0.0, 0.0, 0.0] # начальные весовые коэффициенты
nt = np.array([0.1, 0.05, 0.05]) # шаг обучения для каждого параметра w0, w1, w2
lm = 0.01 # значение параметра лямбда для вычисления EMA
N = 200 # число итераций алгоритма SGD
batch_size = 10 # размер мини-батча (величина K = 10)

alpha = 0.7 # параметр для RMSProp
G = np.zeros(len(w)) # параметр для RMSProp
eps = 0.01 # параметр для RMSProp

# здесь расчет идет через функцию потерь, а не через скобки Айверсона - 
# иначе задание не принимается
Qe = loss(w, X_train, y_train).mean()
np.random.seed(0)

for i in range(N):
    # индекс случайного образа
    k = np.random.randint(0, n_train - batch_size - 1)
    index = k + batch_size # берем выборку из batch_size значений
    Q = np.mean(loss(w, X_train[k:index], y_train[k:index])) # эмпирический риск
    Qe = lm * Q + (1 - lm) * Qe
    # обратить внимание - берется среднее значение по строкам
    grad_Q = df(w, X_train[k:index], y_train[k:index]).mean(axis=1)
    G = alpha * G + (1 - alpha) * grad_Q ** 2
    w = w - nt * grad_Q / (np.sqrt(G) + eps)

# доля неверных классификаций - расчет уже через скобки Айверсона
Q = (w @ X_train.T * y_train < 0).mean()

print(f"Q = {Q}")
print(f"Qe = {Qe}")

